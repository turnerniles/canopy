"""
Canopy — the score.

Home key: D (Lydian-tinged major). 90 BPM, 4/4, every section = 16 bars.
Shared grammar that makes all five sections one piece:
  * every section starts on a D-rooted chord and ends (bar 16) on an A-rooted
    dominant-sus chord; bar 8 is also A-rooted -> any section can follow any
    other at an 8- or 16-bar boundary.
  * the "Canopy motif": A-D-E-A (rising 4th, step, 4th) then a falling 3rd and
    the Lydian #4 (G#) sigh. Every section quotes it, transformed.
  * signature cadence colour: bVI (Bbmaj9) -> bVII (Cmaj9) or bVI -> V.

Melody tuples: (bar 1-16, beat 1..4.99, duration in beats, note)
"""
from synth import nm


def V(s):
    return [nm(x) for x in s.split()]


def ch(label, bass, ep, pad, ep2=None):
    return dict(label=label, bass=nm(bass), ep=V(ep), pad=V(pad), ep2=V(ep2) if ep2 else None)


